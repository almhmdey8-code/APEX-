
create table if not exists public.apex_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  created_at timestamptz not null default now()
);
alter table public.apex_admins enable row level security;
revoke all on public.apex_admins from anon, authenticated;
grant select on public.apex_admins to authenticated;
drop policy if exists "admin can read own admin record" on public.apex_admins;
create policy "admin can read own admin record" on public.apex_admins
for select to authenticated using (user_id = (select auth.uid()));

create table if not exists public.apex_products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default '',
  description text not null default '',
  image_url text not null default '',
  price numeric(12,2),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.apex_products enable row level security;
grant select on public.apex_products to anon, authenticated;
grant insert, update, delete on public.apex_products to authenticated;
drop policy if exists "public reads active products" on public.apex_products;
create policy "public reads active products" on public.apex_products for select to anon, authenticated using (active = true);
drop policy if exists "admins manage products" on public.apex_products;
create policy "admins manage products" on public.apex_products for all to authenticated
using (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())));

create table if not exists public.apex_orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  address text not null,
  items jsonb not null default '[]'::jsonb,
  notes text not null default '',
  status text not null default 'new' check (status in ('new','confirmed','processing','shipped','delivered','cancelled')),
  aramex_tracking_number text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.apex_orders enable row level security;
revoke all on public.apex_orders from anon, authenticated;
grant insert on public.apex_orders to anon, authenticated;
grant select, update on public.apex_orders to authenticated;
drop policy if exists "public can submit orders" on public.apex_orders;
create policy "public can submit orders" on public.apex_orders for insert to anon, authenticated with check (true);
drop policy if exists "admins view orders" on public.apex_orders;
create policy "admins view orders" on public.apex_orders for select to authenticated
using (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())));
drop policy if exists "admins update orders" on public.apex_orders;
create policy "admins update orders" on public.apex_orders for update to authenticated
using (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())));
