create table if not exists public.apex_banners (
  id bigint generated by default as identity primary key,
  title text not null default '',
  subtitle text not null default '',
  image_url text not null default '',
  link_url text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.apex_payment_methods (
  id bigint generated by default as identity primary key,
  name text not null,
  instructions text not null default '',
  method_type text not null default 'manual',
  enabled boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.apex_banners enable row level security;
alter table public.apex_payment_methods enable row level security;
create policy "public reads active banners" on public.apex_banners for select to anon, authenticated using (active = true);
create policy "admins manage banners" on public.apex_banners for all to authenticated using (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid()))) with check (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())));
create policy "public reads enabled payment methods" on public.apex_payment_methods for select to anon, authenticated using (enabled = true);
create policy "admins manage payment methods" on public.apex_payment_methods for all to authenticated using (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid()))) with check (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())));
grant select on public.apex_banners, public.apex_payment_methods to anon, authenticated;
grant insert, update, delete on public.apex_banners, public.apex_payment_methods to authenticated;
grant usage, select on all sequences in schema public to authenticated;