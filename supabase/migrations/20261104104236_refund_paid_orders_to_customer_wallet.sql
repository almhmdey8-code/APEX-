create table if not exists public.apex_order_refunds (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.apex_orders(id) on delete restrict,
  user_id uuid not null,
  amount_sar numeric(12,2) not null check (amount_sar > 0),
  admin_id uuid not null,
  reason text not null default '',
  created_at timestamptz not null default now()
);
alter table public.apex_order_refunds enable row level security;
revoke all on public.apex_order_refunds from anon, authenticated;
grant select on public.apex_order_refunds to authenticated;
drop policy if exists "Admins can view order refunds" on public.apex_order_refunds;
create policy "Admins can view order refunds" on public.apex_order_refunds
for select to authenticated
using (exists (select 1 from public.apex_admins a where a.user_id = (select auth.uid())));

create or replace function public.apex_admin_refund_order_to_wallet(
  p_order_id bigint,
  p_reason text default ''
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_admin uuid := auth.uid();
  v_order public.apex_orders%rowtype;
  v_amount numeric(12,2);
begin
  if v_admin is null or not exists (
    select 1 from public.apex_admins a where a.user_id = v_admin
  ) then
    raise exception 'غير مصرح: هذه العملية للمدير فقط';
  end if;

  select * into v_order
  from public.apex_orders
  where id = p_order_id
  for update;

  if not found then raise exception 'الطلب غير موجود'; end if;
  if v_order.user_id is null then raise exception 'لا يمكن الاسترداد: الطلب غير مرتبط بحساب عميل'; end if;
  if v_order.payment_status <> 'paid' then
    raise exception 'لا يمكن الاسترداد إلا للطلب المدفوع؛ الحالة الحالية: %', v_order.payment_status;
  end if;
  if v_order.total_sar is null or v_order.total_sar <= 0 then
    raise exception 'قيمة الطلب غير صالحة للاسترداد';
  end if;
  if exists (select 1 from public.apex_order_refunds r where r.order_id = p_order_id) then
    raise exception 'تم استرداد هذا الطلب مسبقاً';
  end if;

  v_amount := round(v_order.total_sar, 2);

  insert into public.apex_wallets(user_id,balance_sar,updated_at)
  values (v_order.user_id,0,now())
  on conflict (user_id) do nothing;

  perform 1 from public.apex_wallets w where w.user_id = v_order.user_id for update;

  insert into public.apex_order_refunds(order_id,user_id,amount_sar,admin_id,reason)
  values (p_order_id,v_order.user_id,v_amount,v_admin,left(coalesce(p_reason,''),500));

  update public.apex_wallets
  set balance_sar = balance_sar + v_amount, updated_at = now()
  where user_id = v_order.user_id;

  insert into public.apex_wallet_transactions(
    user_id,amount_sar,transaction_type,description,reference_type,reference_id
  ) values (
    v_order.user_id,v_amount,'refund',
    'استرداد قيمة الطلب #' || p_order_id || ' إلى محفظة APEX',
    'order_refund',p_order_id::text
  );

  update public.apex_orders
  set payment_status = 'refunded', updated_at = now()
  where id = p_order_id;

  update public.apex_orders
  set status = 'cancelled', shipping_status = 'cancelled', updated_at = now()
  where id = p_order_id and status <> 'cancelled';

  return jsonb_build_object(
    'ok',true,'order_id',p_order_id,'user_id',v_order.user_id,
    'amount_sar',v_amount,'payment_status','refunded','wallet_credited',true
  );
end;
$$;
revoke all on function public.apex_admin_refund_order_to_wallet(bigint,text) from public, anon;
grant execute on function public.apex_admin_refund_order_to_wallet(bigint,text) to authenticated;