
alter table public.apex_payment_methods
  add column if not exists account_holder text,
  add column if not exists account_number text,
  add column if not exists account_iban text,
  add column if not exists public_config jsonb not null default '{}'::jsonb,
  add column if not exists secret_key_names text[] not null default '{}'::text[],
  add column if not exists integration_status text not null default 'not_configured',
  add column if not exists integration_tested_at timestamptz;

alter table public.apex_payment_methods
  drop constraint if exists apex_payment_methods_integration_status_check;
alter table public.apex_payment_methods
  add constraint apex_payment_methods_integration_status_check
  check (integration_status in ('not_configured','credentials_missing','sandbox_ready','verified','error'));

create table if not exists public.apex_shipping_providers (
  id bigint generated by default as identity primary key,
  provider_code text not null unique,
  name text not null,
  country_code text not null default 'SA' check (country_code in ('SA','YE','ALL')),
  integration_mode text not null default 'manual' check (integration_mode in ('manual','api')),
  enabled boolean not null default false,
  tracking_url_template text,
  public_config jsonb not null default '{}'::jsonb,
  secret_key_names text[] not null default '{}'::text[],
  integration_status text not null default 'not_configured'
    check (integration_status in ('not_configured','credentials_missing','sandbox_ready','verified','error')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.apex_shipping_providers enable row level security;
drop policy if exists apex_shipping_providers_admin_all on public.apex_shipping_providers;
create policy apex_shipping_providers_admin_all
on public.apex_shipping_providers for all to authenticated
using (exists (select 1 from public.apex_admins a where a.user_id=(select auth.uid())))
with check (exists (select 1 from public.apex_admins a where a.user_id=(select auth.uid())));
grant select,insert,update,delete on public.apex_shipping_providers to authenticated;
grant usage,select on sequence public.apex_shipping_providers_id_seq to authenticated;

